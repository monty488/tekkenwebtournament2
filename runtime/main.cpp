// Entry point: sets up the guest address space, loads the game image, wires the
// recompiled function table and jumps to the XEX entry point.
//
// Web: built with -sPROXY_TO_PTHREAD, so main() already runs on a worker and is
// allowed to block. Game files live in OPFS, mounted at /game by WASMFS.

#include "kernel/guest.h"
#include "kernel/memory.h"
#include "kernel/module.h"
#include "kernel/threads.h"
#include "hid/input.h"
#include "vfs/vfs.h"

#include <cstdio>
#include <filesystem>
#include <fstream>
#include <vector>

#ifdef __EMSCRIPTEN__
#include <emscripten.h>
#include <emscripten/wasmfs.h>
#endif

namespace fs = std::filesystem;

static bool LoadImage(const fs::path& path)
{
    std::ifstream file(path, std::ios::binary | std::ios::ate);
    if (!file)
    {
        TTT2_LOG("missing %s (produced by scripts/scan-xex.ps1)", path.string().c_str());
        return false;
    }
    const auto size = uint64_t(file.tellg());
    if (size > PPC_IMAGE_SIZE)
    {
        TTT2_LOG("image.bin is 0x%llX bytes but this build expects 0x%llX. Was it made from a different XEX?",
            (unsigned long long)size, (unsigned long long)PPC_IMAGE_SIZE);
        return false;
    }
    file.seekg(0);
    file.read(reinterpret_cast<char*>(guest::g_base + PPC_IMAGE_BASE), std::streamsize(size));
    return bool(file);
}

static void InstallFunctionTable()
{
    uint8_t* base = guest::g_base;
    size_t count = 0;
    for (auto* m = PPCFuncMappings; m->host != nullptr; ++m, ++count)
        PPC_LOOKUP_FUNC(base, m->guest) = m->host;
    TTT2_LOG("installed %zu recompiled functions", count);
}

static uint32_t ReadEntryPoint(const fs::path& infoPath)
{
    // image_info.toml is tiny and generated by ttt2-scan; a line scan is enough.
    std::ifstream info(infoPath);
    std::string line;
    while (std::getline(info, line))
    {
        unsigned value = 0;
        if (std::sscanf(line.c_str(), "entry_point = 0x%x", &value) == 1)
            return value;
    }
    return 0;
}

int main(int argc, char** argv)
{
#ifdef __EMSCRIPTEN__
    // web/loader.js copies the user's files into OPFS as files/ and scan/.
    backend_t opfs = wasmfs_create_opfs_backend();
    wasmfs_create_directory("/game", 0777, opfs);
    const fs::path dataRoot = "/game";
#else
    const fs::path dataRoot = argc > 1 ? fs::path(argv[1]) : fs::path("game");
#endif

    TTT2_LOG("Tekken Tag Tournament 2 recompiled runtime (data: %s)", dataRoot.string().c_str());

    vfs::SetGameRoot(dataRoot / "files");

    guest::InstallCrashHandler();

    if (!guest::InitMemory())
        return 1;
    if (!LoadImage(dataRoot / "scan" / "image.bin"))
        return 1;
    InstallFunctionTable();
    if (!guest::InitModule(dataRoot / "scan"))
        return 1;
    hid::Init();
    guest::StartWatchdog();

    const uint32_t entry = ReadEntryPoint(dataRoot / "scan" / "image_info.toml");
    if (!entry)
    {
        TTT2_LOG("could not read entry_point from scan/image_info.toml");
        return 1;
    }

    TTT2_LOG("jumping to entry point 0x%08X", entry);
    const uint32_t result = guest::RunGuestThread(entry, 0);
    TTT2_LOG("guest main thread returned %u", result);
    return int(result);
}
