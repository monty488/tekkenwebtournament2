"""Lists the FFmpeg C sources a configured build needs, without make.

Usage: python -I ffmpeg_sources.py <ffmpeg src dir> <configured build dir>

Reads <build>/ffbuild/config.mak (the CONFIG_*/HAVE_* switches FFmpeg's configure chose)
and the OBJS / OBJS-$(VAR) assignments of libavutil's and libavcodec's Makefiles (with
their includes), and writes <build>/ffmpeg_sources.cmake for runtime/CMakeLists.txt:
FFMPEG_SOURCES (C files), FFMPEG_DEFINES (from CPPFLAGS) and FFMPEG_INCLUDES. Also writes
libavutil/ffversion.h, which FFmpeg's make would generate.
"""
import os
import re
import sys

LIBRARIES = ['libavutil', 'libavcodec']


def read_config(path):
    switches = {}
    values = {}
    with open(path, encoding='utf-8') as f:
        for line in f:
            line = line.rstrip('\n')
            m = re.match(r'^(!?)([A-Z0-9_]+)=(.*)$', line)
            if not m:
                continue
            negated, name, value = m.groups()
            if value == 'yes':
                switches[name] = not negated
            else:
                values[name] = value
    return switches, values


def logical_lines(path):
    with open(path, encoding='utf-8') as f:
        text = f.read().replace('\\\n', ' ')
    return text.splitlines()


def collect(src, makefile, switches, arch, objs):
    """Adds the objects a Makefile enables to objs (an ordered dict used as a set)."""
    if not os.path.exists(makefile):
        return
    for line in logical_lines(makefile):
        line = line.strip()
        inc = re.match(r'^-?include\s+(.*)$', line)
        if inc:
            path = inc.group(1).replace('$(SRC_PATH)', src).replace('$(ARCH)', arch)
            collect(src, path, switches, arch, objs)
            continue
        m = re.match(r'^OBJS(?:-\$\(([A-Z0-9_]+)\))?\s*\+?=\s*(.*)$', line)
        if not m:
            continue
        var, files = m.groups()
        if var and not switches.get(var, False):
            continue
        for name in files.split():
            if name.endswith('.o'):
                objs[name] = True


def main():
    src, build = (os.path.abspath(p) for p in sys.argv[1:3])
    switches, values = read_config(os.path.join(build, 'ffbuild', 'config.mak'))
    arch = values.get('ARCH', 'c')

    sources = []
    for lib in LIBRARIES:
        objs = {}
        collect(src, os.path.join(src, lib, 'Makefile'), switches, arch, objs)
        for obj in objs:
            c = os.path.join(src, lib, obj[:-2] + '.c')
            if os.path.exists(c):
                sources.append(c)
            else:
                print(f'note: no C source for {lib}/{obj} (skipped)', file=sys.stderr)

    defines = [d[2:] for d in values.get('CPPFLAGS', '').split() if d.startswith('-D')]
    includes = [build, src]
    for flag in values.get('CPPFLAGS', '').split():
        if flag.startswith('-I'):
            includes.append(flag[2:].replace('$(SRC_PATH)', src))

    with open(os.path.join(build, 'libavutil', 'ffversion.h'), 'w', encoding='utf-8') as f:
        version = open(os.path.join(src, 'VERSION_FETCHED'), encoding='utf-8').read().strip()
        f.write('#ifndef AVUTIL_FFVERSION_H\n#define AVUTIL_FFVERSION_H\n')
        f.write(f'#define FFMPEG_VERSION "{version}"\n#endif\n')

    def cmake_list(items):
        return '\n'.join('    "' + i.replace('\\', '/') + '"' for i in items)

    with open(os.path.join(build, 'ffmpeg_sources.cmake'), 'w', encoding='utf-8') as f:
        f.write('# Generated by scripts/ffmpeg_sources.py\n')
        f.write('set(FFMPEG_SOURCES\n' + cmake_list(sources) + '\n)\n')
        f.write('set(FFMPEG_DEFINES\n' + cmake_list(defines) + '\n)\n')
        f.write('set(FFMPEG_INCLUDES\n' + cmake_list(includes) + '\n)\n')
    print(f'{len(sources)} sources -> {os.path.join(build, "ffmpeg_sources.cmake")}')


if __name__ == '__main__':
    main()
