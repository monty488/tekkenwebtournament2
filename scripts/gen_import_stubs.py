"""Generates recomp/generated/import_stubs.cpp.

Every kernel/XAM import the game uses (game/scan/imports.txt, written by
ttt2-scan) must have a definition or the link fails. This script finds which
ones runtime/ already implements with GUEST_IMPORT(Name) and emits a logging
GUEST_IMPORT_STUB(Name) for the rest, then prints a coverage report.

Run with: python -I scripts/gen_import_stubs.py
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
IMPORTS = ROOT / "game" / "scan" / "imports.txt"
RUNTIME = ROOT / "runtime"
OUTPUT = ROOT / "recomp" / "generated" / "import_stubs.cpp"

IMPLEMENTED_RE = re.compile(r"^\s*GUEST_IMPORT\(\s*(\w+)\s*\)", re.MULTILINE)


def main() -> int:
    if not IMPORTS.exists():
        print(f"error: {IMPORTS} not found; run scripts/scan-xex.ps1 first", file=sys.stderr)
        return 1

    imports = sorted({
        line.strip().removeprefix("__imp__")
        for line in IMPORTS.read_text().splitlines()
        if line.strip()
    })

    implemented = set()
    for source in RUNTIME.rglob("*.cpp"):
        implemented.update(IMPLEMENTED_RE.findall(source.read_text(encoding="utf-8", errors="replace")))

    missing = [name for name in imports if name not in implemented]

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    lines = [
        "// GENERATED by scripts/gen_import_stubs.py - do not edit.",
        "// Imports the game links against that runtime/ does not implement yet.",
        "// Implement one with GUEST_IMPORT(Name) anywhere under runtime/ and re-run the script.",
        "",
        '#include "kernel/guest.h"',
        "",
    ]
    lines += [f"GUEST_IMPORT_STUB({name})" for name in missing]
    OUTPUT.write_text("\n".join(lines) + "\n")

    done = len(imports) - len(missing)
    print(f"imports: {len(imports)}  implemented: {done}  stubbed: {len(missing)}")
    print(f"wrote {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
