// ttt2-scan: inspects the game's default.xex using XenonUtils and produces the
// inputs the rest of the pipeline needs, so nobody has to hunt for them by hand.
//
//   ttt2-scan <default.xex> <output directory>
//
// Outputs:
//   image.bin               decrypted + decompressed guest image (loaded by the runtime at PPC_IMAGE_BASE)
//   image_info.toml         base/size/entry point/section table
//   recomp_addresses.toml   register save/restore helper addresses for recomp/config/TTT2.toml
//   imports.txt             every kernel/XAM import the game links against (one __imp__ name per line)

#include <cstdio>
#include <cstring>
#include <filesystem>
#include <fstream>
#include <optional>
#include <string>
#include <vector>

#include <file.h>
#include <image.h>

namespace fs = std::filesystem;

struct Pattern
{
    const char* key;
    std::vector<uint8_t> bytes;
};

// Byte patterns documented in XenonRecomp's README. Each one matches the first
// instruction(s) of the corresponding compiler helper.
static const Pattern kPatterns[] =
{
    { "restgprlr_14_address", { 0xE9, 0xC1, 0xFF, 0x68 } },
    { "savegprlr_14_address", { 0xF9, 0xC1, 0xFF, 0x68 } },
    { "restfpr_14_address",   { 0xC9, 0xCC, 0xFF, 0x70 } },
    { "savefpr_14_address",   { 0xD9, 0xCC, 0xFF, 0x70 } },
    { "restvmx_14_address",   { 0x39, 0x60, 0xFE, 0xE0, 0x7D, 0xCB, 0x60, 0xCE } },
    { "savevmx_14_address",   { 0x39, 0x60, 0xFE, 0xE0, 0x7D, 0xCB, 0x61, 0xCE } },
    { "restvmx_64_address",   { 0x39, 0x60, 0xFC, 0x00, 0x10, 0x0B, 0x60, 0xCB } },
    { "savevmx_64_address",   { 0x39, 0x60, 0xFC, 0x00, 0x10, 0x0B, 0x61, 0xCB } },
};

static std::vector<size_t> FindAll(const Image& image, const std::vector<uint8_t>& needle)
{
    std::vector<size_t> hits;
    for (const auto& section : image.sections)
    {
        if ((section.flags & SectionFlags_Code) == 0 || section.data == nullptr)
            continue;

        // Instructions are 4-byte aligned, so only test aligned offsets.
        for (size_t off = 0; off + needle.size() <= section.size; off += 4)
        {
            if (memcmp(section.data + off, needle.data(), needle.size()) == 0)
                hits.push_back(section.base + off);
        }
    }
    return hits;
}

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        fprintf(stderr, "Usage: ttt2-scan <default.xex> <output directory>\n");
        return 1;
    }

    const fs::path xexPath = argv[1];
    const fs::path outDir = argv[2];

    auto file = LoadFile(xexPath);
    if (file.empty())
    {
        fprintf(stderr, "error: could not read %s\n", xexPath.string().c_str());
        return 1;
    }

    Image image = Image::ParseImage(file.data(), file.size());
    if (image.data == nullptr)
    {
        fprintf(stderr, "error: %s is not a XEX2/ELF image (or decryption failed)\n", xexPath.string().c_str());
        return 1;
    }

    fs::create_directories(outDir);

    {
        std::ofstream bin(outDir / "image.bin", std::ios::binary);
        bin.write(reinterpret_cast<const char*>(image.data.get()), image.size);
    }

    {
        std::ofstream info(outDir / "image_info.toml");
        info << "# Generated by ttt2-scan from " << xexPath.filename().string() << "\n";
        char buf[256];
        snprintf(buf, sizeof(buf), "base = 0x%08zX\nsize = 0x%08X\nentry_point = 0x%08zX\n\n",
            image.base, image.size, image.entry_point);
        info << buf;
        for (const auto& section : image.sections)
        {
            snprintf(buf, sizeof(buf), "[[section]]\nname = \"%s\"\nbase = 0x%08zX\nsize = 0x%08X\ncode = %s\n\n",
                section.name.c_str(), section.base, section.size,
                (section.flags & SectionFlags_Code) ? "true" : "false");
            info << buf;
        }
    }

    {
        std::ofstream imports(outDir / "imports.txt");
        size_t count = 0;
        for (const auto& symbol : image.symbols)
        {
            if (symbol.name.rfind("__imp__", 0) == 0)
            {
                imports << symbol.name << "\n";
                ++count;
            }
        }
        printf("imports: %zu\n", count);
    }

    {
        std::ofstream toml(outDir / "recomp_addresses.toml");
        toml << "# Generated by ttt2-scan. Paste into the [main] table of recomp/config/TTT2.toml.\n";
        toml << "# Entries with more than one candidate need checking in a disassembler.\n";
        bool ambiguous = false;
        for (const auto& pattern : kPatterns)
        {
            auto hits = FindAll(image, pattern.bytes);
            char buf[128];
            if (hits.size() == 1)
            {
                snprintf(buf, sizeof(buf), "%s = 0x%08zX\n", pattern.key, hits[0]);
                toml << buf;
            }
            else
            {
                ambiguous = true;
                toml << "# " << pattern.key << ": " << hits.size() << " candidates";
                for (size_t hit : hits)
                {
                    snprintf(buf, sizeof(buf), " 0x%08zX", hit);
                    toml << buf;
                }
                toml << "\n";
            }
            printf("%-22s %zu hit(s)\n", pattern.key, hits.size());
        }
        if (ambiguous)
            printf("warning: some helpers were not found exactly once; see recomp_addresses.toml\n");
    }

    printf("wrote %s\n", outDir.string().c_str());
    return 0;
}
